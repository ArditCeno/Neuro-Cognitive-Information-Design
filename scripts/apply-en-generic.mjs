/*
 * Generic EN applier. Reads every scripts/en/<id>.json and applies:
 *   - generates materials/<id>_<exp>_m<N>_<a|b>.en.html (EN facts + AL code + figure)
 *   - sets materials.en paths and translated quiz text (q.en / options.en)
 *   - rewrites js/fields.js
 *
 * en/<id>.json shape:
 * {
 *   "id": "legal", "en_name": "Law",
 *   "modules": {
 *     "fillestar|m1": { "title": "M1 - Elements of an article",
 *        "facts": ["...", ...],
 *        "qA": [["question", ["o1","o2","o3","o4"], correctIndex], ...],
 *        "qB": [ ... ] },
 *     ...
 *   }
 * }
 *
 * node scripts/apply-en-generic.mjs
 * Copyright 2026 Ardit Ceno. All rights reserved.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { FIELDS, EXPERTISE, PROFESSIONS } from "../js/fields.js";

function esc(s) { return String(s).replace(/[&<>]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;" }[c])); }
function codeOf(html) { const m = html.match(/<pre>[\s\S]*?<\/pre>/); return m ? "\n" + m[0] : ""; }
const fig = (id) => `<img class="fig" src="../assets/figures/${id}.svg" alt="${id} figure">`;

const dir = "scripts/en";
if (!existsSync(dir)) { console.log("no scripts/en dir"); process.exit(0); }

let applied = 0;
for (const file of readdirSync(dir).filter((f) => f.endsWith(".json"))) {
  const data = JSON.parse(readFileSync(dir + "/" + file, "utf8"));
  const field = FIELDS.find((f) => f.id === data.id);
  if (!field) { console.warn("no field for", data.id); continue; }
  for (const exp of Object.keys(data.modules)) {
    const [expId, mId] = exp.split("|");
    const mod = (field.expertise[expId] || { modules: [] }).modules.find((m) => m.id === mId);
    if (!mod) { console.warn("no module", data.id, exp); continue; }
    const en = data.modules[exp];
    const alA = readFileSync(mod.materials.A.al, "utf8");
    const code = codeOf(alA);
    const title = en.title || mod.title;
    const head = `<h1>${esc(data.en_name)} - ${esc(expId)} - ${esc(title)}</h1>\n${fig(data.id)}`;
    const itemsA = en.facts.map((f, i) => `<li${i === en.facts.length - 1 ? ' data-aoi="kritike" data-critical="true"' : ""}>${esc(f)}</li>`).join("\n");
    const joined = en.facts.map((f, i) => i === en.facts.length - 1 ? `<span data-aoi="kritike" data-critical="true">${esc(f)}</span>` : esc(f)).join(" ");
    const pathA = `materials/${data.id}_${expId}_${mId}_a.en.html`;
    const pathB = `materials/${data.id}_${expId}_${mId}_b.en.html`;
    writeFileSync(pathA, `${head}\n<ul>\n${itemsA}\n</ul>${code}\n`);
    writeFileSync(pathB, `${head}\n<p>${joined}</p>${code}\n`);
    mod.materials.A.en = pathA;
    mod.materials.B.en = pathB;
    if (en.qA) mod.quiz.A.forEach((q, i) => { const t = en.qA[i]; if (t) { q.q.en = t[0]; q.options.forEach((o, j) => { o.en = t[1][j]; }); } });
    if (en.qB) mod.quiz.B.forEach((q, i) => { const t = en.qB[i]; if (t) { q.q.en = t[0]; q.options.forEach((o, j) => { o.en = t[1][j]; }); } });
    applied++;
  }
}

const js = `/*
 * Generated by scripts/import-pack.mjs + scripts/apply-en-generic.mjs.
 * EN translations applied where scripts/en/*.json exist (others fall back to AL).
 * Copyright 2026 Ardit Ceno. All rights reserved.
 */
export const EXPERTISE = ${JSON.stringify(EXPERTISE, null, 2)};
export const COMPLEXITY = { m1: "basic", m2: "intermediate", m3: "advanced" };
export const PROFESSIONS = ${JSON.stringify(PROFESSIONS, null, 2)};
export const FIELDS = ${JSON.stringify(FIELDS, null, 2)};
`;
writeFileSync("js/fields.js", js);
console.log(`applied EN to ${applied} modules; fields.js rewritten`);
