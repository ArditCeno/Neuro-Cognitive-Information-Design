/*
 * Imports the real content pack (Kuize_Interaktive.html / PDF) into the app.
 *   node scripts/import-pack.mjs "C:/Users/User/Downloads/Kuize_Interaktive.html"
 *
 * Generates:
 *   materials/<id>_<exp>_m<N>_<a|b>.al.html   (real A/B content)
 *   js/fields.js                               (modules + quizzes A/B)
 * EN files are pointed to the AL files until real translations are added.
 *
 * Copyright 2026 Ardit Ceno. All rights reserved.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const src = process.argv[2];
if (!src) { console.error("usage: node scripts/import-pack.mjs <path-to-Kuize_Interaktive.html>"); process.exit(1); }

const html = readFileSync(src, "utf8");
const start = html.indexOf("const D=");
if (start < 0) { console.error("data array not found"); process.exit(1); }
const bodyStart = start + "const D=".length;
// find matching end of the JSON array
let depth = 0, end = bodyStart;
for (let i = bodyStart; i < html.length; i++) {
  const c = html[i];
  if (c === "[" || c === "{") depth++;
  else if (c === "]" || c === "}") { depth--; if (depth === 0) { end = i + 1; break; } }
}
const D = JSON.parse(html.slice(bodyStart, end));

const MAP = {
  "Informatikë": { id: "software", en: "Software", al: "Informatikë" },
  "Drejtësi": { id: "legal", en: "Law", al: "Drejtësi" },
  "Financë": { id: "finance", en: "Finance", al: "Financë" },
  "Biznes": { id: "business", en: "Business", al: "Biznes" },
  "Mjekësi": { id: "health", en: "Medicine", al: "Mjekësi" },
  "Infermieri": { id: "nurse", en: "Nursing", al: "Infermieri" },
  "Pedagogji": { id: "pedagogue", en: "Pedagogy", al: "Pedagogji" },
  "Biologji": { id: "biologist", en: "Biology", al: "Biologji" },
  "Bioteknologji": { id: "biotech", en: "Biotechnology", al: "Bioteknologji" },
  "Kimi": { id: "chemist", en: "Chemistry", al: "Kimi" },
  "Inxhinieri elektrike": { id: "electrical", en: "Electrical engineering", al: "Inxhinieri elektrike" },
  "Kuzhinieri": { id: "cook", en: "Culinary", al: "Kuzhinieri" }
};
const LEVEL = { "Fillestar": "fillestar", "Mid": "mid", "Senior": "senior" };
const esc = (s) => String(s).replace(/[&<>]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;" }[c]));

function materialHTML(p, exp, title, mod, version) {
  const head = `<h1>${esc(p.al)} - ${esc(exp)} - ${esc(title)}</h1>`;
  const code = mod.code ? `<h2>Kod / formulë</h2><pre><code>${esc(mod.code)}</code></pre>` : "";
  if (version === "A") {
    const items = mod.facts.map((f, i) => `<li${i === mod.facts.length - 1 ? ' data-aoi="kritike" data-critical="true"' : ""}>${esc(f)}</li>`).join("\n");
    return `<h1>${esc(p.al)} - ${esc(exp)} - ${esc(title)}</h1>\n<ul>\n${items}\n</ul>\n${code}\n`;
  }
  const joined = mod.facts.map((f, i) => i === mod.facts.length - 1
    ? `<span data-aoi="kritike" data-critical="true">${esc(f)}</span>` : esc(f)).join(" ");
  return `<h1>${esc(p.al)} - ${esc(exp)} - ${esc(title)}</h1>\n<p>${joined}</p>\n${code}\n`;
}

function quizItem(q) {
  return {
    q: { en: q.q, al: q.q },  // EN text pending translation; AL source reused
    options: q.o.map((o) => ({ en: o, al: o })),
    correct: q.a,
    critical: !!q.c
  };
}

mkdirSync("materials", { recursive: true });

const out = [];
for (const p of D) {
  const info = MAP[p.name];
  if (!info) { console.warn("unknown profession:", p.name); continue; }
  const levels = { fillestar: { modules: [] }, mid: { modules: [] }, senior: { modules: [] } };
  let counter = {};
  p.mods.forEach((mod) => {
    const expId = LEVEL[mod.level];
    counter[expId] = (counter[expId] || 0) + 1;
    const mN = counter[expId];
    const mid = "m" + mN;
    // split quizzes: A = even, B = odd
    const quizA = mod.qs.filter((_, i) => i % 2 === 0).map(quizItem);
    const quizB = mod.qs.filter((_, i) => i % 2 === 1).map(quizItem);
    const aPath = `materials/${info.id}_${expId}_${mid}_a.al.html`;
    const bPath = `materials/${info.id}_${expId}_${mid}_b.al.html`;
    writeFileSync(aPath, materialHTML(info, mod.level, mod.title, mod, "A"));
    writeFileSync(bPath, materialHTML(info, mod.level, mod.title, mod, "B"));
    levels[expId].modules.push({
      id: mid,
      complexity: { m1: "basic", m2: "intermediate", m3: "advanced" }[mid],
      title: mod.title,
      materials: {
        A: { al: aPath, en: aPath },
        B: { al: bPath, en: bPath }
      },
      quiz: { A: quizA, B: quizB }
    });
  });
  out.push({ id: info.id, name: { en: info.en, al: info.al }, expertise: levels });
}

const js = `/*
 * Generated by scripts/import-pack.mjs — real content pack.
 * Copyright 2026 Ardit Ceno. All rights reserved.
 */
export const EXPERTISE = [
  { id: "fillestar", al: "Fillestar", en: "Beginner" },
  { id: "mid", al: "Mid", en: "Mid" },
  { id: "senior", al: "Senior", en: "Senior" }
];
export const COMPLEXITY = { m1: "basic", m2: "intermediate", m3: "advanced" };
export const PROFESSIONS = ${JSON.stringify(out.map((f) => ({ id: f.id, al: f.name.al, en: f.name.en })), null, 2)};
export const FIELDS = ${JSON.stringify(out, null, 2)};
`;
writeFileSync("js/fields.js", js);
console.log(`imported ${out.length} professions, ${out.reduce((s, f) => s + f.expertise.fillestar.modules.length + f.expertise.mid.modules.length + f.expertise.senior.modules.length, 0)} modules`);
